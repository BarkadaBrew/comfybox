  private func syntheticCheckpoint(weightScale: Float = 0) -> [String: MLXArray] {
    var w: [String: MLXArray] = [:]
    for (k, shape) in Self.vocoderFixture {
      if weightScale != 0 && (k.hasSuffix(".weight") || k.hasSuffix(".filter")
          || k.hasSuffix(".alpha") || k.hasSuffix(".beta")) {
        w[k] = MLXRandom.normal(shape) * MLXArray(weightScale)
      } else {
        w[k] = MLXArray.zeros(shape)
      }
    }
    return w
  }

  func testFixtureHasAll1227Tensors() {
    XCTAssertEqual(Self.vocoderFixture.count, 1227)
  }

  func testModuleParameterCountMatchesCheckpoint() {
    let v = LTX2Vocoder()
    XCTAssertEqual(v.parameters().flattened().count, 1227)
  }

  /// Anti-noise guard: every remapped checkpoint key hits a real module param.
  func testEveryCheckpointKeyMapsToAModuleParameter() {
    let v = LTX2Vocoder()
    let moduleKeys = Set(v.parameters().flattened().map { $0.0 })
    let remapped = LTX2Vocoder.remapKeys(syntheticCheckpoint())
    XCTAssertEqual(remapped.count, 1227)
    var matched = 0
    for (k, _) in remapped {
      if moduleKeys.contains(k) { matched += 1 }
      else { XCTFail("remapped key has no module param: \(k)") }
    }
    XCTAssertEqual(matched, 1227)
  }

  /// Weights apply with shape verification (proves conv OIK→OKI and ConvT
  /// IOK→OKI transposes and every channel count), guard reports 1227/1227.
  func testLoadWeightsAppliesWithShapeVerification() throws {
    let v = LTX2Vocoder()
    let (matched, total) = try v.loadWeightsFromTensors(
      tensors: syntheticCheckpoint(), logger: Logger(label: "test.vocoder"))
    XCTAssertEqual(total, 1227)
    XCTAssertEqual(matched, 1227)
  }

  func testLoadThrowsOnNearZeroCoverage() {
    let v = LTX2Vocoder()
    let junk: [String: MLXArray] = ["vocoder.vocoder.bogus.weight": MLXArray.zeros([4, 4, 3])]
    XCTAssertThrowsError(
      try v.loadWeightsFromTensors(tensors: junk, logger: Logger(label: "test.vocoder")))
  }

  /// Synthesis produces the exact upsampled sample count (frames × ∏rates = ×160)
  /// with 2 (stereo) channels.
  func testSynthesizeProducesCorrectSampleCount() throws {
    let v = LTX2Vocoder()
    _ = try v.loadWeightsFromTensors(
      tensors: syntheticCheckpoint(weightScale: 0.05), logger: Logger(label: "test.vocoder"))
    let frames = 4
    let mel = MLXRandom.normal([1, 128, frames])
    let wave = v.synthesize(mel)
    MLX.eval(wave)
    XCTAssertEqual(wave.shape, [1, 2, frames * 160], "waveform shape wrong: \(wave.shape)")
  }

  /// Output is finite, bounded by tanh, and NOT silent (guards a dead graph).
  func testSynthesizeIsFiniteAndNonSilent() throws {
    let v = LTX2Vocoder()
    _ = try v.loadWeightsFromTensors(
      tensors: syntheticCheckpoint(weightScale: 0.1), logger: Logger(label: "test.vocoder"))
    let mel = MLXRandom.normal([1, 128, 4])
    let wave = v.synthesize(mel)
    MLX.eval(wave)
    let maxAbs = MLX.max(MLX.abs(wave)).item(Float.self)
    XCTAssertTrue(maxAbs.isFinite, "vocoder produced non-finite output")
    XCTAssertLessThanOrEqual(maxAbs, 1.0 + 1e-4, "tanh bound violated: \(maxAbs)")
    XCTAssertGreaterThan(maxAbs, 1e-4, "vocoder produced (near-)silence: \(maxAbs)")
  }
